#include <iostream>
#include <stdlib.h>
using namespace std;

int main() {
    int A[100]; // берем массив с запасом места под добавление нулей
    int n = 12;

    cout << "Исходный массив: ";
    for (int i = 0; i < n; i++) {
        A[i] = rand() % 90 + 10; // заполняем числами от 10 до 99
        cout << A[i] << " ";
    }
    cout << endl;

    int K;
    cout << "Введите номер элемента K (от 1 до " << n << "): ";
    cin >> K;

    // 2) Печать по кольцу ВЛЕВО (от K-го элемента)
    cout << "Кольцо влево:  ";
    int curr = K - 1; // индекс на 1 меньше номера
    for (int step = 0; step < n; step++) {
        cout << A[curr] << " ";
        curr--;
        if (curr < 0) curr = n - 1; // переход от первого к последнему
    }
    cout << endl;

    // 3) Добавление 0 после элементов с индексами кратными 5 (0, 5, 10...)
    for (int i = n - 1; i >= 0; i--) {
        if (i % 5 == 0) {
            // сдвигаем все элементы правее на 1 шаг вправо
            for (int j = n; j > i + 1; j--) {
                A[j] = A[j - 1];
            }
            A[i + 1] = 0; // вставляем 0 после индекса i
            n++;          // размер массива вырос на 1
        }
    }

    cout << "Массив после вставки нулей: ";
    for (int i = 0; i < n; i++) cout << A[i] << " ";
    cout << endl;

    // 4) Печать по кольцу ВПРАВО (от K-го элемента)
    cout << "Кольцо вправо: ";
    curr = K - 1;
    for (int step = 0; step < n; step++) {
        cout << A[curr] << " ";
        curr++;
        if (curr == n) curr = 0; // переход от последнего к первому
    }
    cout << endl;

    return 0;
}
