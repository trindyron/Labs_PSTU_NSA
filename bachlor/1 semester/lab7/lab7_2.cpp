#include <iostream>
using namespace std;

// Макрос проверки существования треугольника (сумма двух сторон больше третьей)
#define IS_TRIANGLE(x, y, z) (((x) + (y) > (z)) && ((x) + (z) > (y)) && ((y) + (z) > (x)))

// Функция с переменным числом параметров
// k - обязательный параметр, указывающий количество передаваемых чисел
int triangle(int k, ...) {
    int *p = &k; // Настраиваем указатель на первый параметр (по методичке)
    int arr[20]; // Временный массив для удобства
    int count = 0;

    // Считываем все переменные параметры в массив
    for (int i = 0; i < k; i++) {
        arr[i] = *(++p);
    }

    // Проверяем тройки рядом расположенных чисел
    for (int i = 0; i < k - 2; i++) {
        if (IS_TRIANGLE(arr[i], arr[i+1], arr[i+2])) {
            count++;
        }
    }
    
    return count;
}

int main() {
    // Первый аргумент - количество последующих чисел
    cout << "Вызов 1 (3 параметра): " << triangle(3, 3, 4, 5) << endl;
    cout << "Вызов 2 (9 параметров): " << triangle(9, 1, 2, 3, 2, 2, 2, 10, 10, 10) << endl;
    cout << "Вызов 3 (11 параметров): " << triangle(11, 3, 4, 5, 5, 4, 3, 1, 1, 1, 2, 2) << endl;

    return 0;
}
